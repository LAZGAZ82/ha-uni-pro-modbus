W = H = 9


def to_xbm(art):
    rows = [r for r in art.strip("\n").split("\n")]
    assert len(rows) == H, f"{len(rows)} rows"
    out = []
    for r in rows:
        assert len(r) == W, f"'{r}' has {len(r)} cols"
        b0 = 0
        b1 = 0
        for x, ch in enumerate(r):
            if ch == "#":
                if x < 8:
                    b0 |= 1 << x
                else:
                    b1 |= 1 << (x - 8)
        out += [b0, b1]
    return out


def main():
    print("// Automatisch erzeugt von tools/gen_icons.py - nicht von Hand bearbeiten.")
    print("#pragma once")
    print("#include <stdint.h>")
    print()
    print("#define IRD_ICON_W 9")
    print("#define IRD_ICON_H 9")
    print()
    names = []
    for key, label, art in ICONS:
        names.append((key, label))
        if art is None:
            continue
        data = to_xbm(art)
        print(f"static const uint8_t ird_icon_{key.lower()}_bits[] = {{")
        line = "    " + ", ".join(f"0x{b:02x}" for b in data)
        print(line)
        print("};")
    print()
    print("typedef enum {")
    for key, _ in names:
        print(f"    IrdIcon{key},")
    print("    IrdIconCount,")
    print("} IrdIcon;")
    print()
    print("typedef struct {")
    print("    const char* name;")
    print("    const uint8_t* bits;")
    print("} IrdIconDef;")
    print()
    print("static const IrdIconDef ird_icon_table[IrdIconCount] = {")
    for key, label in names:
        bits = "NULL" if key == "None" else f"ird_icon_{key.lower()}_bits"
        print(f'    [IrdIcon{key}] = {{"{label}", {bits}}},')
    print("};")


if __name__ == "__main__":
    main()
